/** Filled cells of a text line (unknown characters render as spaces), plus its size in pixels. */
export function textCells(text: string): { width: number; height: number; cells: [number, number][] } {
  const chars = [...text.toUpperCase()];
  const cells: [number, number][] = [];
  chars.forEach((ch, i) => {
    const glyph = GLYPHS[ch] ?? GLYPHS[' '];
    const x0 = i * (GLYPH_W + GLYPH_GAP);
    glyph.forEach((row, y) => {
      for (let x = 0; x < GLYPH_W; x++) if (row[x] === '#') cells.push([x0 + x, y]);
    });
  });
  const width = chars.length === 0 ? 0 : chars.length * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP;
  return { width, height: GLYPH_H, cells };
}

/** One SVG path for a set of cells: horizontal runs become "M x y h n v 1 h -n z". */
export function cellsToPath(cells: readonly (readonly [number, number])[], dx = 0, dy = 0): string {
  const rows = new Map<number, number[]>();
  for (const [x, y] of cells) {
    const list = rows.get(y) ?? [];
    list.push(x);
    rows.set(y, list);
  }
  let d = '';
  for (const [y, xs] of [...rows.entries()].sort((a, b) => a[0] - b[0])) {
    xs.sort((a, b) => a - b);
    let i = 0;
    while (i < xs.length) {
      let end = i + 1;
      while (end < xs.length && xs[end] === xs[end - 1] + 1) end++;
      const run = end - i;
      d += `M${xs[i] + dx} ${y + dy}h${run}v1h${-run}z`;
      i = end;
    }
  }
  return d;
}
